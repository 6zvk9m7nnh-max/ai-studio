import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(resolve('fitness-web/index.html')).href);
await page.getByRole('button',{name:/Salle/}).first().click();
assert.ok(await page.getByText('Presse à cuisses').count()===0,'Program list should not show individual exercises');
await page.getByRole('button',{name:/Commencer/}).first().click();
assert.ok(await page.getByText('Développé poitrine machine').count()>0,'Gym workout did not start');
await page.getByRole('button',{name:/Série 1/}).first().click();
assert.ok(await page.getByText(/Repos/).count()>0,'Rest timer did not start');
await page.getByRole('button',{name:/Terminer et enregistrer/}).click();
assert.ok(await page.getByText('Historique').count()>0,'History did not open');
await page.getByRole('button',{name:/Profil/}).click();
await page.locator('#name').fill('Testeur');
await page.getByRole('button',{name:/Enregistrer mon profil/}).click();
await page.reload();
await page.getByRole('button',{name:/Profil/}).click();
assert.equal(await page.locator('#name').inputValue(),'Testeur','Profile did not persist');
assert.deepEqual(errors,[],'JavaScript errors: '+errors.join('; '));
await browser.close();
console.log('Safari-style mobile viewport: all primary controls passed browser test.');
